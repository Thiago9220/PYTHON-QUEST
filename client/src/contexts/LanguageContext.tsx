export type TranslationKey = keyof typeof TRANSLATIONS.pt;

type LanguageContextType = {
  lang: AppLanguage;
  setLang: (lang: AppLanguage) => void;
  toggleLang: () => void;
  t: (key: TranslationKey) => string;
};

const LanguageContext = createContext<LanguageContextType | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<AppLanguage>(getSavedLanguage);

  const setLang = (next: AppLanguage) => {
    setLangState(next);
    if (typeof window !== "undefined") {
      localStorage.setItem("python_quest_lang", next);
    }
  };

  const toggleLang = () => setLang(lang === "pt" ? "en" : "pt");
  const t = (key: TranslationKey) => TRANSLATIONS[lang][key] ?? TRANSLATIONS.pt[key];

  return (
    <LanguageContext.Provider value={{ lang, setLang, toggleLang, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error("useLanguage must be used within LanguageProvider");
  return ctx;
}

export function isScreenShakeEnabled(): boolean {
  if (typeof window === "undefined") return true;
  const saved = localStorage.getItem("python_quest_screen_shake");
  return saved === null ? true : saved === "true";
}

export function setScreenShakeEnabled(enabled: boolean): void {
  if (typeof window !== "undefined") {
    localStorage.setItem("python_quest_screen_shake", enabled ? "true" : "false");
  }
}
